CREATE TABLE public.trauma_sections (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  key text NOT NULL UNIQUE,
  title text NOT NULL,
  subtitle text,
  body text,
  image_url text,
  primary_label text,
  primary_url text,
  secondary_label text,
  secondary_url text,
  sort_order integer NOT NULL DEFAULT 0,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

GRANT SELECT ON public.trauma_sections TO anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.trauma_sections TO authenticated;
GRANT ALL ON public.trauma_sections TO service_role;

ALTER TABLE public.trauma_sections ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Anyone can view active trauma sections" ON public.trauma_sections
  FOR SELECT TO anon, authenticated USING (is_active = true);
CREATE POLICY "Admins can view all trauma sections" ON public.trauma_sections
  FOR SELECT TO authenticated USING (has_role(auth.uid(), 'admin'::app_role));
CREATE POLICY "Admins can insert trauma sections" ON public.trauma_sections
  FOR INSERT TO authenticated WITH CHECK (has_role(auth.uid(), 'admin'::app_role));
CREATE POLICY "Admins can update trauma sections" ON public.trauma_sections
  FOR UPDATE TO authenticated USING (has_role(auth.uid(), 'admin'::app_role));
CREATE POLICY "Admins can delete trauma sections" ON public.trauma_sections
  FOR DELETE TO authenticated USING (has_role(auth.uid(), 'admin'::app_role));

CREATE TRIGGER trauma_sections_set_updated_at BEFORE UPDATE ON public.trauma_sections
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

